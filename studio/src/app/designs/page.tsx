'use client'

import { useState, useEffect } from 'react'
import Link from 'next/link'
import { Sparkles, ArrowLeft, Download, PlusCircle, Image as ImageIcon } from 'lucide-react'

export default function DesignsVaultPage() {
  const [designs, setDesigns] = useState<any[]>([])
  const [loading, setLoading] = useState(true)

  useEffect(() => {
    async function load() {
      try {
        const res = await fetch('/api/designs')
        if (res.ok) {
          const data = await res.json()
          setDesigns(data.designs || [])
        }
      } catch (e) {
        console.error('Error fetching designs', e)
      } finally {
        setLoading(false)
      }
    }
    load()
  }, [])

  return (
    <div className="min-h-screen bg-slate-950 text-slate-100 flex flex-col">
      <header className="border-b border-slate-800 bg-slate-900/60 backdrop-blur px-6 py-4 flex items-center justify-between">
        <div className="flex items-center gap-4">
          <Link
            href="/dashboard"
            className="p-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 transition"
          >
            <ArrowLeft className="w-4 h-4" />
          </Link>
          <div>
            <h1 className="text-lg font-bold text-white flex items-center gap-2">
              <Sparkles className="w-4 h-4 text-indigo-400" />
              My Generated Designs Vault
            </h1>
            <p className="text-xs text-slate-400">All banners and marketing creatives generated by your business</p>
          </div>
        </div>

        <Link
          href="/create-design"
          className="inline-flex items-center gap-2 px-4 py-2 bg-indigo-600 hover:bg-indigo-500 text-white rounded-xl text-xs font-semibold shadow-md transition"
        >
          <PlusCircle className="w-3.5 h-3.5" />
          Create New Design
        </Link>
      </header>

      <main className="max-w-7xl w-full mx-auto p-6 sm:p-10 flex-1">
        {loading ? (
          <div className="p-16 text-center text-slate-500 bg-slate-900/40 rounded-2xl border border-slate-800">
            Loading your design gallery...
          </div>
        ) : designs.length === 0 ? (
          <div className="bg-slate-900 border border-slate-800 rounded-2xl p-12 text-center space-y-4">
            <div className="w-16 h-16 rounded-2xl bg-indigo-500/10 border border-indigo-500/20 flex items-center justify-center mx-auto text-indigo-400">
              <ImageIcon className="w-8 h-8" />
            </div>
            <h3 className="text-lg font-semibold text-white">Vault is empty</h3>
            <p className="text-sm text-slate-400 max-w-sm mx-auto">
              You haven't generated any designs yet. Generate an AI banner or poster tailored to your brand!
            </p>
            <Link
              href="/create-design"
              className="inline-flex items-center gap-2 px-5 py-2.5 bg-indigo-600 hover:bg-indigo-500 text-white rounded-xl text-sm font-semibold transition"
            >
              <PlusCircle className="w-4 h-4" />
              Generate First Design
            </Link>
          </div>
        ) : (
          <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 lg:grid-cols-4 gap-6">
            {designs.map((design) => (
              <div
                key={design.id}
                className="group bg-slate-900 border border-slate-800 rounded-2xl overflow-hidden hover:border-slate-700 transition flex flex-col shadow-xl"
              >
                <div className="relative aspect-square bg-slate-950 flex items-center justify-center overflow-hidden">
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img
                    src={design.image_path}
                    alt={design.title || 'Creative'}
                    className="w-full h-full object-cover group-hover:scale-105 transition duration-300"
                  />
                </div>
                <div className="p-4 flex-1 flex flex-col justify-between">
                  <div>
                    <h4 className="font-semibold text-sm text-white line-clamp-1">{design.title}</h4>
                    <p className="text-xs text-slate-400 mt-1 line-clamp-2">
                      {design.prompt?.brief?.topic || 'AI Creative'}
                    </p>
                  </div>
                  <div className="pt-3 mt-3 border-t border-slate-800/80 flex items-center justify-between">
                    <span className="text-[11px] text-slate-500">
                      {new Date(design.created_at).toLocaleDateString()}
                    </span>
                    <a
                      href={design.image_path}
                      download={`creative_${design.id}.png`}
                      target="_blank"
                      rel="noreferrer"
                      className="inline-flex items-center gap-1 text-xs text-indigo-400 hover:text-indigo-300 font-medium"
                    >
                      <Download className="w-3.5 h-3.5" /> Download
                    </a>
                  </div>
                </div>
              </div>
            ))}
          </div>
        )}
      </main>
    </div>
  )
}
